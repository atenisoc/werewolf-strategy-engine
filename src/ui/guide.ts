import { ROLES } from '../game/roles';
import type { RoleId } from '../game/types';
import type { HumanRequest } from '../game/engine';

// 初心者向けの「いま何をするところか」の説明
export function guideText(req: HumanRequest | null, role: RoleId, day: number, finished: boolean): string {
  if (finished) return 'ゲーム終了です。「AI思考を見る」で、各AIがなぜそう判断したかを確認できます。';
  if (!req) return '進行中です。発言をよく読んで、誰が怪しいか考えながら待ちましょう。';
  const r = ROLES[role];
  if (req.type === 'talk') {
    const base = '【昼の話し合い】怪しい人を疑ったり、信頼できる人をかばったりして意見を出します。迷ったら「様子見」でも大丈夫です。';
    const extra =
      role === 'seer' ? ' あなたは占い師。結果を伝える「占い師CO」をすると村の信用を得やすくなります（ただし人狼に狙われやすくなります）。'
      : role === 'medium' ? ' あなたは霊能者。処刑された人の白黒を伝えると、占い師が本物か見分ける手がかりになります。'
      : role === 'hunter' ? ' あなたは狩人。正体は隠したほうが安全です。疑われてピンチのときだけCOしましょう。'
      : role === 'werewolf' ? ' あなたは人狼。村人のふりをしましょう。仲間は疑わず、占い師を騙る（偽CO）作戦もあります。'
      : role === 'madman' ? ' あなたは狂人。占い師（または霊能者）を騙って村を混乱させると人狼側が有利になります。'
      : role === 'mason' ? ' あなたは共有者。相方は確定で白です。2人でCOすると「確定で白い人」として信用され、議論を引っ張れます。'
      : role === 'fox' ? ' あなたは妖狐。目立たず最後まで生き残れば単独勝ちです。人狼には噛まれませんが、占われると死ぬので、占い師の目を引かないようにしましょう。'
      : ' あなたは村人。占い師の結果と、みんなの投票の動きを手がかりにしましょう。';
    return base + extra + (day === 1 ? (req.obs.config.day1Vote ? ' 初日は情報が少ないので、「占い師はCOして」と促すのも定番です。' : ' このゲームは初日の処刑がありません。今日は情報集めの日です。「占い師はCOして」と促すのも定番です。') : '');
  }
  if (req.type === 'vote') return '【投票】一番怪しいと思う人に投票します。最多得票の人が処刑されます。同数なら決選投票です。';
  if (req.type === 'plan') return '【初夜・作戦会議】人狼だけの相談です。誰が占い師を騙るか（騙らないのもあり）、偽の占いで仲間に白を出す「囲い」をするか、仲間が吊られそうなときに自分も投票して村人のふりをする「身内切り」をするかを決めます。仲間のAIはこの取り決めに従います。';
  if (req.kind === 'divine') return '【夜】占い師の時間。誰を占いますか？ 疑わしい人、まだ白黒がわからない人が狙い目です。結果は「白＝人狼ではない／黒＝人狼」です。';
  if (req.kind === 'guard') return '【夜】狩人の時間。守る人を選びます。人狼に襲われそうな人（本物らしい占い師など）を守ると、襲撃を防げます。' + (req.obs.config.noConsecutiveGuard ? '同じ人を2晩続けて守ることはできません。' : 'この村では同じ人を続けて守れます。');
  return `【夜】人狼の時間。今夜襲う人を選びます。${r.tips}`;
}

