export interface RenderCtx {
  nameOf: (id: number) => string;
  tone: Tone;
  rng: Rng;
  recent?: Map<string, number[]>; // 直近に使ったテンプレ番号(同じ文ばかりにならないように)
  pref?: string; // 話者の県名(口調レイヤー。省略時は標準語)
  gender?: 'm' | 'f'; // 話者の性別(女性は文末を柔らかく)
  self?: number; // 話者の席。自分自身に言及するときは名前ではなく「私」にする
  greet?: boolean; // 初日の第一声に挨拶を添える
  todayTexts?: string[]; // 今日すでに出た発言(他人が使った言い回しを避ける。同じ文が同じ日に並ぶと不自然)
}

// テンプレの「固定部分」(名前の穴を除いた一番長い文字列)。今日の発言にこれが含まれていれば同じ言い回しとみなす
function literalOf(tpl: string): string {
  const segs = tpl.split(/\{\w\}/).map((x) => x.replace(/^[、。]+|[、。]+$/g, ''));
  return segs.sort((a, b) => b.length - a.length)[0] ?? '';
}
function usedToday(tpl: string, ctx: RenderCtx): boolean {
  if (!ctx.todayTexts?.length) return false;
  const lit = literalOf(tpl);
  if (lit.length < 5) return false;
  // 方言・性別で文末が変わるので、固定部分の先頭側(最大10文字)で照合する
  const probe = lit.slice(0, 10);
  return ctx.todayTexts.some((t) => t.includes(probe));
}

function pickFrom(list: string[], key: string, ctx: RenderCtx): string {
  const recent = ctx.recent?.get(key) ?? [];
  let idx = list.map((_, i) => i).filter((i) => !recent.includes(i));
  if (idx.length === 0) idx = list.map((_, i) => i);
  // 今日ほかの人が使った言い回しは避ける(全部使われていたらやむなく重複)
  const fresh = idx.filter((i) => !usedToday(list[i], ctx));
  if (fresh.length) idx = fresh;
  const i = idx[ctx.rng.int(idx.length)];
  if (ctx.recent) ctx.recent.set(key, [...recent, i].slice(-Math.max(1, Math.min(3, list.length - 1))));
  return list[i];
}
function pickPool(pool: Pool, key: string, ctx: RenderCtx): string {
  const list = pool[ctx.tone].length ? pool[ctx.tone] : pool.plain;
  return pickFrom(list, key + ':' + ctx.tone, ctx);
}
