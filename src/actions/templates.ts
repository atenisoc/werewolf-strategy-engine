export function renderStatement(st: Statement, ctx: RenderCtx): string {
  const body = renderBase(st, ctx);
  // 初日の第一声は挨拶から(「おはよう」「よろしく」+ 本題)。CO文は挨拶→CO の順になる
  const text = ctx.greet ? pickPool(GREET, 'greet', ctx) + body : body;
  return applyDialect(applyGender(text, ctx.gender), ctx.pref);
}

function renderBase(st: Statement, ctx: RenderCtx): string {
  const nm = (i: number) => (i === ctx.self ? '私' : ctx.nameOf(i));
  const p = st.target != null ? nm(st.target) : '';
  const s = st.ref != null ? nm(st.ref) : '';
  const c = st.color ? colorWord(st.color) : '';
  const reason = st.reason ? REASON_TEXT[st.reason] : '';
  switch (st.kind) {
    case 'accuse':
      if (st.tag === 'answer' && st.ref != null) return fill(pickPool(st.ref === st.target ? accuseAnswerSelf : accuseAnswer, 'accuse:answer', ctx), { p, s }) + reason;
      return fill(pickPool(st.tag === 'mild' ? accuseMild : st.tag === 'hard' ? accuseHard : accuse, 'accuse:' + (st.tag ?? ''), ctx), { p }) + reason;
    case 'defend_self':
      return fill(pickPool(defendSelf[st.tag ?? 'ask_back'] ?? defendSelf.ask_back, 'defend_self:' + (st.tag ?? ''), ctx), { p });
    case 'disagree':
      return fill(pickPool(disagree, 'disagree', ctx), { p, s });
    case 'defend':
      return fill(pickPool(defend, 'defend', ctx), { p });
    case 'agree':
      return fill(pickPool(agree, 'agree', ctx), { p, s });
    case 'wait':
      if (st.tag === 'asked' && st.ref != null) return fill(pickPool(waitAsked, 'wait_asked', ctx), { s });
      return pickPool(ctx.greet ? waitDay1 : wait, ctx.greet ? 'wait1' : 'wait', ctx);
    case 'vote_intent':
      return fill(pickPool(voteIntent, 'vote_intent', ctx), { p }) + (st.reason ? reason : '');
    case 'ask_co':
      return pickFrom(askCo, 'ask_co', ctx);
    case 'propose':
      return fill(pickPool(propose[st.plan ?? 'grey'], 'propose:' + st.plan, ctx), { p });
    case 'vote_review':
      return fill(pickPool(voteReview, 'vote_review', ctx), { p, s });
    case 'attack_review':
      return fill(pickPool(attackReview, 'attack_review', ctx), { p });
    case 'medium_review':
      return fill(pickPool(mediumReview, 'medium_review', ctx), { p });
    case 'line':
      return fill(pickPool(line, 'line', ctx), { p, s });
    case 'waver':
      return fill(pickPool(waver, 'waver', ctx), { p, s });
    case 'bite_logic':
      return fill(pickPool(st.color === 'white' ? biteWhite : biteBlack, 'bite:' + st.color, ctx), { p, s });
    case 'count':
      return fill(pickFrom(st.n != null && st.m != null && st.n <= 2 * st.m + 2 ? countTight : countLoose, 'count', ctx), { n: String(st.n ?? ''), m: String(st.m ?? '') });
    case 'confirm':
      return st.reason === 'broken' || st.ref == null ? fill(pickPool(confirmBroken, 'confirm:b', ctx), { p }) : fill(pickPool(confirmAttacked, 'confirm:a', ctx), { p, s });
    case 'co_timing':
      return fill(pickPool(st.tag === 'late' ? coLate : coEarly, 'co_timing:' + st.tag, ctx), { p });
    case 'ask':
      return fill(pickPool(ask, 'ask', ctx), { p });
    case 'silent_point':
      return fill(pickPool(silentPoint, 'silent_point', ctx), { p });
    case 'co': {
      const r = st.claim as RoleId;
      if (r === 'seer') return st.target != null ? fill(pickFrom(coSeer, 'co_seer', ctx), { p, c }) : pickFrom(coSeerBare, 'co_seer_b', ctx);
      if (r === 'medium') return st.target != null ? fill(pickFrom(coMedium, 'co_med', ctx), { p, c }) : pickFrom(coMediumBare, 'co_med_b', ctx);
      if (r === 'hunter') return pickFrom(coHunter, 'co_hunter', ctx);
      if (r === 'mason') return pickFrom(coMason, 'co_mason', ctx);
      return `${claimName[r] ?? r}COします。`;
    }
    case 'result': {
      if (st.claim === 'hunter') return fill(pickFrom(resHunter, 'res_hunter', ctx), { p });
      if (st.claim === 'medium') return fill(pickFrom(resMedium, 'res_medium', ctx), { p, c });
      const base = fill(pickFrom(resSeer, 'res_seer', ctx), { p, c });
      if (!st.why) return base;
      const whyList = (st.color === 'black' && resSeerWhyBlack[st.why]) || resSeerWhy[st.why];
      return base + pickFrom(whyList, 'why:' + st.why + (st.color === 'black' ? ':b' : ''), ctx);
    }
  }
}
