export const DIALECT_PREFS = Object.keys(RULES);

// 文字列から 0〜1 の疑似乱数を作る(FNV-1a)
function hash01(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return (h >>> 8) / 0x01000000;
}

// 1文に規則を適用(最初に一致した1つだけ)
function applyOne(sentence: string, rules: Rule[]): string {
  for (const [re, rep] of rules) if (re.test(sentence)) return sentence.replace(re, rep);
  return sentence;
}

/**
 * 発言テキストに県の口調を乗せる。
 * @param text 標準語の発言
 * @param pref 県名(CHARACTERS[i].name)。規則がなければそのまま返す
 * @param rate 1文ごとに適用する確率(既定0.7)。全文を方言にすると読みにくいので間引く
 */
export function applyDialect(text: string, pref: string | undefined, rate = 0.7): string {
  const rules = pref ? RULES[pref] : undefined;
  if (!rules || !rules.length) return text;
  // 「。」で文に分け、文ごとに判定する(最後の文が「。」で終わらないこともある)
  const parts = text.match(/[^。？]*[。？]|[^。？]+$/g) ?? [text];
  return parts
    .map((s, i) => (hash01(`${pref}|${i}|${s}`) < rate ? applyOne(s, rules) : s))
    .join('');
}

// 性別による言葉遣い(立ち絵の性別に合わせる)。テンプレートは男性寄りの常体なので、女性キャラは文末を柔らかくする。
// 方言より先に適用する(「だ。」→「ね。」にしてから県の語尾をかぶせる)
const FEMALE_RULES: Rule[] = [
  [/だろう。$/, 'でしょう。'], [/だろ。$/, 'でしょ。'], [/だよな。$/, 'だよね。'], [/だな。$/, 'ね。'], [/だ。$/, 'ね。'],
  [/じゃないか。$/, 'じゃない？'], [/ないか。$/, 'ない？'], [/のか。$/, 'の？'],
  [/してくれ。$/, 'して。'], [/てくれ。$/, 'て。'], [/言え。$/, '言って。'], [/しろ。$/, 'して。'], [/考えろ。$/, '考えて。'], [/始めるぞ。$/, '始めましょう。'], [/ぞ。$/, 'わよ。'],
  [/聞かない。$/, '聞かないわ。'], [/吊る以外ない。$/, '吊るしかないわ。'],
];
export function applyGender(text: string, gender: 'm' | 'f' | undefined): string {
  if (gender !== 'f') return text;
  const parts = text.match(/[^。？]*[。？]|[^。？]+$/g) ?? [text];
  return parts.map((s) => applyOne(s, FEMALE_RULES)).join('');
}
